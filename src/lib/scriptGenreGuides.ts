/** 取命中标签的创作要点（最多 max 条），返回可直接拼进 prompt 的多行文本。 */
export function buildGuideBlock(
  tags: string[],
  dict: Record<string, string>,
  max = 4,
): string {
  const lines: string[] = [];
  for (const tag of tags) {
    const key = tag.trim();
    const guide = dict[key];
    if (guide) lines.push(`- ${key}：${guide}`);
    if (lines.length >= max) break;
  }
  return lines.join("\n");
}
